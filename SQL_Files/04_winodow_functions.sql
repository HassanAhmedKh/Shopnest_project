--Tier 4, Query 1, business question: For every product, show its name, category_id, price, and its price rank within
-- its own category (1 = most expensive).

SELECT PRODUCT_ID, PRODUCT_NAME, CATEGORY_ID, PRICE,
	RANK () OVER (PARTITION BY CATEGORY_ID ORDER BY PRICE DESC) AS PRICE_RANK
FROM PRODUCTS
ORDER BY category_id, price_rank;

--Tier 4, Query 2: top N per group.
--Business question: For each city, find the top 3 customers by total completed-order spend. Show the city, customer name, total spend, and rank.

SELECT CITY, FULL_NAME, TOTAL_SPENT, SPEND_RANK

FROM

(SELECT CUSTOMERS.CUSTOMER_ID, CUSTOMERS.CITY, CUSTOMERS.FULL_NAME, SUM(ORDER_ITEMS.QUANTITY * ORDER_ITEMS.UNIT_PRICE) AS TOTAL_SPENT,
	RANK() OVER (PARTITION BY CUSTOMERS.CITY ORDER BY  SUM(ORDER_ITEMS.QUANTITY * ORDER_ITEMS.UNIT_PRICE) DESC) AS SPEND_RANK

FROM CUSTOMERS
JOIN ORDERS
ON CUSTOMERS.CUSTOMER_ID = ORDERS.CUSTOMER_ID

JOIN ORDER_ITEMS
ON ORDERS.ORDER_ID = ORDER_ITEMS.ORDER_ID
WHERE ORDERS.STATUS = 'completed'
GROUP BY CUSTOMERS.CUSTOMER_ID,CUSTOMERS.CITY, CUSTOMERS.FULL_NAME)
AS RANKED
WHERE SPEND_RANK <= 3

ORDER BY CITY, SPEND_RANK;

--Tier 4, Query 3: running totals.
--Business question: Show monthly revenue for completed orders, plus a running (cumulative) total, so each month shows total revenue from the start of the data up to and including that month.

SELECT TO_CHAR(DATE_TRUNC('MONTH',ORDERS.ORDER_DATE), 'YYYY-MM') AS MONTHS
, SUM(ORDER_ITEMS.UNIT_PRICE *ORDER_ITEMS.QUANTITY)
AS TOTAL_REVENUE,
SUM(SUM(ORDER_ITEMS.QUANTITY * ORDER_ITEMS.UNIT_PRICE)) OVER (ORDER BY TO_CHAR(DATE_TRUNC('MONTH',ORDERS.ORDER_DATE), 'YYYY-MM'))
AS RUNNING_REVENUE
FROM ORDERS
JOIN ORDER_ITEMS
ON ORDERS.ORDER_ID = ORDER_ITEMS.ORDER_ID

WHERE ORDERS.STATUS = 'completed'
GROUP BY DATE_TRUNC('MONTH',ORDERS.ORDER_DATE)
ORDER BY DATE_TRUNC('MONTH',ORDERS.ORDER_DATE);

--Tier 4, Query 4: comparing a row to the previous row with LAG.
--Business question: Show monthly revenue for completed orders, the previous month’s revenue next to it, and the month-over-month percentage change.

SELECT MONTHS,REVENUE,PREVIOUS_MONTH_REVENUE,ROUND((REVENUE - PREVIOUS_MONTH_REVENUE) * 100.0 / PREVIOUS_MONTH_REVENUE,1) AS PERCT
FROM

(SELECT DATE_TRUNC('month', ORDERS.ORDER_DATE)::DATE AS MONTHS,
SUM(ORDER_ITEMS.QUANTITY * ORDER_ITEMS.UNIT_PRICE) AS REVENUE,
LAG( SUM(ORDER_ITEMS.QUANTITY * ORDER_ITEMS.UNIT_PRICE) ) OVER ( ORDER BY DATE_TRUNC('month', ORDERS.ORDER_DATE))AS PREVIOUS_MONTH_REVENUE
FROM ORDERS
JOIN ORDER_ITEMS
ON ORDERS.ORDER_ID = ORDER_ITEMS.ORDER_ID
WHERE ORDERS.STATUS = 'completed'
GROUP BY DATE_TRUNC('month', ORDERS.ORDER_DATE))
AS MONTHLY
ORDER BY MONTHS;

--Tier 4, Query 5: first order per customer with ROW_NUMBER.
--Business question: For each customer, show their first completed order: customer name, order_id, and order_date.

SELECT FULL_NAME,ORDER_ID,ORDER_DATE
FROM
(SELECT CUSTOMERS.FULL_NAME, ORDERS.ORDER_ID, ORDERS.ORDER_DATE,
ROW_NUMBER() OVER (PARTITION BY CUSTOMERS.CUSTOMER_ID ORDER BY ORDERS.ORDER_DATE, ORDERS.ORDER_ID ASC ) AS RN
FROM CUSTOMERS
JOIN ORDERS
ON CUSTOMERS.CUSTOMER_ID = ORDERS.CUSTOMER_ID
WHERE ORDERS.STATUS = 'completed')
AS RANKED
WHERE RN = 1
ORDER BY FULL_NAME;

--Tier 4, Query 6: resubscribers with LAG on dates.

--Business question: For customers who had more than one Prime subscription, show each subscription’s start date,
--the previous subscription’s end date, and the number of days between them.

SELECT FULL_NAME, START_DATE, PREV_END_DATE, START_DATE - PREV_END_DATE AS DAYS_GAP
FROM
(SELECT CUSTOMERS.FULL_NAME, CUSTOMER_SUBSCRIPTIONS.START_DATE,
LAG(CUSTOMER_SUBSCRIPTIONS.END_DATE) OVER (PARTITION BY CUSTOMERS.CUSTOMER_ID ORDER BY CUSTOMER_SUBSCRIPTIONS.START_DATE)
PREV_END_DATE
FROM CUSTOMERS
JOIN CUSTOMER_SUBSCRIPTIONS
ON CUSTOMERS.CUSTOMER_ID = CUSTOMER_SUBSCRIPTIONS.CUSTOMER_ID
) AS IN_TABLE
WHERE PREV_END_DATE IS NOT NULL
ORDER BY DAYS_GAP;
