-- TIER 1 QUERY 1
-- COMPLETED ORDER WITH CUSTOMER ID, FULL NAME, CITY

SELECT ORDERS.ORDER_ID,CUSTOMERS.FULL_NAME,CUSTOMERS.CITY,SUM(ORDER_ITEMS.QUANTITY) AS TOTAL_ITEMS  
FROM ORDERS 

JOIN CUSTOMERS 
ON ORDERS.CUSTOMER_ID = CUSTOMERS.CUSTOMER_ID 

JOIN ORDER_ITEMS
ON ORDER_ITEMS.ORDER_ID = ORDERS.ORDER_ID

WHERE ORDERS.STATUS = 'completed'
GROUP BY ORDERS.ORDER_ID, CUSTOMERS.FULL_NAME, CUSTOMERS.CITY;

-- TIER 1 QUERY 2
-- List all completed orders along with the customer's name, city, and the total number of items in that order.
SELECT CATEGORIES.CATEGORY_NAME,SUM(ORDER_ITEMS.QUANTITY * ORDER_ITEMS.UNIT_PRICE) AS TOTAL_REVENUE
FROM CATEGORIES

JOIN PRODUCTS
ON CATEGORIES.CATEGORY_ID = PRODUCTS.CATEGORY_ID

JOIN ORDER_ITEMS
ON PRODUCTS.PRODUCT_ID = ORDER_ITEMS.PRODUCT_ID

JOIN ORDERS
ON ORDER_ITEMS.ORDER_ID = ORDERS.ORDER_ID

WHERE ORDERS.STATUS = 'completed'
GROUP BY CATEGORIES.CATEGORY_NAME;